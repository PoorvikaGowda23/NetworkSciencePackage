"""
experiments/step13_diffusion.py
================================
Replicates Figure 4 from Guerrini et al. (EPJ Data Science 2026):
linking the inferred memory parameter p to the speed of diffusion on
synthetic temporal networks generated by generate_memory_graph.

Workflow
--------
For each d in DIFFUSION_D_VALUES and alpha in DIFFUSION_ALPHA_GRID:
  1. Generate DIFFUSION_N_GRAPHS synthetic TemporalGraphs
     (GEN_N nodes, GEN_T snapshots, m_hat = GEN_M_HAT).
  2. For each graph:
     a. Sample NUM_PATHS TRPs, build records at m = DIFFUSION_M_FIT,
        fit MEM to get p_hat.
     b. Run DIFFUSION_RUNS independent diffusion trajectories (each
        starting from a different random seed node) and record the
        final normalized Shannon entropy.
     c. Average the entropy over the DIFFUSION_RUNS runs.
  3. Collect (p_hat, avg_entropy) pairs across graphs.

Figure (2 panels like Figure 4 of the paper)
---------------------------------------------
Left panel:  p_hat vs alpha.
  - Line = median across graphs; shaded band = 5th–95th percentile.
  - One color per d value.
Right panel: avg_entropy vs p_hat.
  - Scatter of individual graph points, smoothed with a running median.
  - One color per d value.

Saved outputs
-------------
results/step13_diffusion.png    Two-panel figure.
results/step13_diffusion.csv    Numerical data for all (d, alpha, graph) triples.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))
sys.path.insert(0, str(Path(__file__).parent.parent))

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.cm as cm

from config import (
    DIFFUSION_ALPHA_GRID,
    DIFFUSION_BETA,
    DIFFUSION_CLIP_WARN,
    DIFFUSION_D_VALUES,
    DIFFUSION_M_FIT,
    DIFFUSION_N_GRAPHS,
    DIFFUSION_RUNS,
    GEN_M_HAT,
    GEN_N,
    GEN_T,
    PATH_LENGTH,
    RANDOM_SEED,
    STEP13_NUM_PATHS,
    RESULTS_DIR,
    T_RES_SECONDS,
)
from memory_trp.diffusion import run_diffusion
from memory_trp.generator import generate_memory_graph
from memory_trp.models import fit_mem_fixed_point
from memory_trp.plotting import plot_diffusion_figure4
from memory_trp.records import build_records
from memory_trp.trp import generate_many_trps


# ---------------------------------------------------------------------------
# Core sweep function
# ---------------------------------------------------------------------------

def run_sweep(rng: np.random.Generator) -> list[dict]:
    """Run the full (d, alpha, graph) sweep and return a list of result rows.

    Each row is a dict with keys:
        d, alpha, graph_idx, p_hat, avg_entropy, entropy_std
    """
    rows: list[dict] = []
    n_d = len(DIFFUSION_D_VALUES)
    n_alpha = len(DIFFUSION_ALPHA_GRID)
    total_configs = n_d * n_alpha
    done = 0

    for d in DIFFUSION_D_VALUES:
        for alpha in DIFFUSION_ALPHA_GRID:
            done += 1
            t0 = time.time()
            p_hats: list[float] = []
            avg_entropies: list[float] = []

            for g_idx in range(DIFFUSION_N_GRAPHS):
                # 1. Generate synthetic graph
                g = generate_memory_graph(
                    n=GEN_N,
                    T=GEN_T,
                    d=d,
                    alpha=alpha,
                    m_hat=GEN_M_HAT,
                    rng=rng,
                    t_res=T_RES_SECONDS,
                    name=f"syn_d{d}_a{alpha:.2f}_g{g_idx}",
                    verbose=False,
                )

                # 2a. Fit MEM
                paths = generate_many_trps(
                    g,
                    num_paths=STEP13_NUM_PATHS,
                    length=PATH_LENGTH,
                    rng=rng,
                )
                records = build_records(paths, m=DIFFUSION_M_FIT)
                p_hat = fit_mem_fixed_point(records, n=GEN_N).p
                p_hats.append(p_hat)

                # 2b. Run diffusion
                entropies: list[float] = []
                for _ in range(DIFFUSION_RUNS):
                    h = run_diffusion(g, beta=DIFFUSION_BETA, rng=rng)
                    entropies.append(h)

                avg_ent = float(np.mean(entropies))
                std_ent = float(np.std(entropies))
                avg_entropies.append(avg_ent)

                rows.append({
                    "d": d,
                    "alpha": alpha,
                    "graph_idx": g_idx,
                    "p_hat": p_hat,
                    "avg_entropy": avg_ent,
                    "std_entropy": std_ent,
                })

            elapsed = time.time() - t0
            print(
                f"  [{done}/{total_configs}] d={d:.0f} alpha={alpha:.1f} | "
                f"p_hat: {np.mean(p_hats):.3f} +/- {np.std(p_hats):.3f} | "
                f"entropy: {np.mean(avg_entropies):.3f} +/- {np.std(avg_entropies):.3f} | "
                f"{elapsed:.1f}s",
                flush=True,
            )

    return rows


# ---------------------------------------------------------------------------
# Plotting (Figure 4 style)
# ---------------------------------------------------------------------------

def plot_figure4(df: pd.DataFrame, output_path: Path) -> None:
    """Delegate to centralized plot_diffusion_figure4 in memory_trp.plotting."""
    title_suffix = (
        f"(n={GEN_N}, T={GEN_T}, m_hat={GEN_M_HAT}, "
        f"beta={DIFFUSION_BETA}, {DIFFUSION_RUNS} diffusion runs/graph)"
    )
    plot_diffusion_figure4(df, output_path, title_suffix=title_suffix)
    print(f"Saved Figure 4 analogue -> {output_path}", flush=True)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def run_step13_pipeline() -> None:
    """Run the memory-vs-diffusion sweep and generate Figure 4."""
    print("=" * 70, flush=True)
    print("Step 13 — Diffusion on synthetic memory graphs (Figure 4)", flush=True)
    print(f"n={GEN_N}, T={GEN_T}, m_hat={GEN_M_HAT}, beta={DIFFUSION_BETA}", flush=True)
    print(f"alpha grid: {DIFFUSION_ALPHA_GRID}", flush=True)
    print(f"d values  : {DIFFUSION_D_VALUES}", flush=True)
    print(f"Graphs/config: {DIFFUSION_N_GRAPHS} | Paths/graph: {STEP13_NUM_PATHS:,} | Diffusion runs: {DIFFUSION_RUNS}", flush=True)
    print("=" * 70, flush=True)

    rng = np.random.default_rng(RANDOM_SEED)
    t_start = time.time()

    rows = run_sweep(rng)

    df = pd.DataFrame(rows)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = RESULTS_DIR / "step13_diffusion.csv"
    df.to_csv(csv_path, index=False)
    print(f"\nSaved CSV -> {csv_path}", flush=True)

    plot_figure4(df, RESULTS_DIR / "step13_diffusion.png")

    elapsed = time.time() - t_start
    print(f"\nStep 13 complete in {elapsed:.1f}s ({elapsed / 60:.2f} min).", flush=True)


if __name__ == "__main__":
    run_step13_pipeline()
